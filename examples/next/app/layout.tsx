import { ValProvider } from "@valbuild/next";
import { config } from "../val.config";
import { ValModulesClient } from "./ValModulesClient";
import { fetchValDraft } from "../val/rsc";
import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en">
      <body className={inter.className}>
        {/*
         * `draft`: the editor's draft, read for this request, so a draft page
         * is rendered as the draft on the server and hydrated from the same
         * thing. `null` for a visitor, after one `draftMode()` lookup.
         */}
        <ValProvider config={config} suspend draft={await fetchValDraft()}>
          <ValModulesClient />
          {children}
        </ValProvider>
      </body>
    </html>
  );
}
