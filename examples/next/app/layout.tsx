import { ValProvider } from "@valbuild/next";
import { config } from "../val.config";
import { ValModulesClient } from "./ValModulesClient";
import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";

const inter = Inter({ subsets: ["latin"] });

// Live mode renders content that was saved in Val but not yet deployed. Next
// only revalidates a prerendered page if something in its render said so, and
// Val's in-process cache means the live fetch usually does not run - so say it
// here instead, matching the `live.ttl` in val.config.ts. Without this, pages
// that are prerendered at build time would never pick up live content.
export const revalidate = 60;

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en">
      <body className={inter.className}>
        <ValProvider config={config} suspend>
          <ValModulesClient />
          {children}
        </ValProvider>
      </body>
    </html>
  );
}
