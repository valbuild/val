#!/usr/bin/env node
/**
 * Fixture helper for the `.jsonValues()` manual walkthrough
 * (see docs/plans/jsonValues-walkthrough.md).
 *
 * The walkthrough mutates the example app on purpose — it renames, deletes and
 * publishes entries — so every step needs a way back to a known state. That is
 * what this script is for:
 *
 *   pnpm fixtures status            what is on disk right now
 *   pnpm fixtures generate [count]  (re)generate the big kb record (default 120)
 *   pnpm fixtures corrupt [count]   make N kb entries invalid JSON (default 3)
 *   pnpm fixtures restore           un-corrupt them
 *   pnpm fixtures nested on|off     add/remove a NESTED jsonValues module (V9)
 *   pnpm fixtures reset             discard all walkthrough edits + drafts
 *
 * Dependency-free on purpose: it runs with plain node.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(scriptDir, "..");

const KB_MODULE = path.join(appDir, "content", "kb.val.ts");
const KB_ENTRIES_DIR = path.join(appDir, "content", "kb");
const NESTED_MODULE = path.join(appDir, "content", "nestedJsonValues.val.ts");
const VAL_MODULES = path.join(appDir, "val.modules.ts");
const NESTED_REGISTRY_LINE =
  '  { def: () => import("./content/nestedJsonValues.val") },';

const DEFAULT_ENTRY_COUNT = 120;
const DEFAULT_CORRUPT_COUNT = 3;

/**
 * The one entry that is deliberately different: it is the ONLY referrer of the
 * `kimmid` author and of the `/support/faq` route, and it sits far enough down
 * the list that you have to scroll to it. V17 renames those and checks the guard
 * still finds this entry.
 */
const ODD_ONE_OUT_INDEX = 113;

/**
 * Paths the walkthrough is allowed to dirty, relative to this app. Git is always
 * run with the app as its cwd, so `reset` can never reach outside it.
 */
const FIXTURE_PATHS = [
  "app/support",
  "content/kb",
  "content/kb.val.ts",
  "content/featuredContent.val.ts",
  "content/tags.val.ts",
  "content/authors.val.ts",
  "val.modules.ts",
];

function entryFileName(index) {
  return `entry-${String(index).padStart(3, "0")}.val.json`;
}

function entryKey(index) {
  return `kb-${String(index).padStart(3, "0")}`;
}

function entryContent(index) {
  const odd = index === ODD_ONE_OUT_INDEX;
  return {
    title: odd
      ? `KB ${index}: the one the walkthrough renames against`
      : `KB article ${index}`,
    body: odd
      ? "This entry is the ONLY referrer of the kimmid author and of the /support/faq route. It is far enough down the list that you have to scroll to reach it."
      : `Body of knowledge-base article ${index}. Searchable token: kbtoken${index}.`,
    order: index,
    author: odd ? "kimmid" : "freekh",
    // Ordinary entries point OUT of the support router on purpose: if all 120
    // pointed at a support page, deleting that page would report 120 references
    // and no walkthrough step could clear them. Only the odd one out references
    // /support/faq, so a rename there has exactly one referrer to rewrite.
    related: odd ? "/support/faq" : "/generic",
  };
}

function kbModuleSource(count) {
  const entries = [];
  for (let i = 0; i < count; i++) {
    entries.push(
      `    "${entryKey(i)}": c.json(() => import("./kb/${entryFileName(i)}")),`,
    );
  }
  return `import { s, c, type t } from "../val.config";
import authorsVal from "./authors.val";

// GENERATED by scripts/jsonvalues-fixtures.mjs — do not hand-edit.
// Regenerate with a different size: pnpm fixtures generate 1000

/**
 * A big \`.jsonValues()\` RECORD (not a router), used by the manual walkthrough
 * in docs/plans/jsonValues-walkthrough.md.
 *
 * Two properties of the ITEM schema are what make it interesting:
 * - \`author: s.keyOf(authorsVal)\` points OUTWARD at an ordinary module, so
 *   renaming an author is the case where the reference guard MUST load every
 *   entry before it can answer (the load predicate names this module).
 * - \`related: s.route()\` triggers the route over-approximation: a route schema
 *   records no target module, so renaming ANY route key has to load this module.
 */
export const kbArticleSchema = s.object({
  title: s.string().minLength(2),
  body: s.string().render({ as: "textarea" }),
  order: s.number(),
  author: s.keyOf(authorsVal),
  related: s.route(),
});

export type KbArticle = t.inferSchema<typeof kbArticleSchema>;

export default c.define(
  "/content/kb.val.ts",
  s
    .record(kbArticleSchema)
    .jsonValues()
    .render({
      as: "list",
      select: ({ val }) => ({
        title: val.title,
        subtitle: val.body,
      }),
    }),
  {
${entries.join("\n")}
  },
);
`;
}

const NESTED_MODULE_SOURCE = `import { s, c } from "../val.config";

// Added by \`pnpm fixtures nested on\` for walkthrough step V9, which checks that
// the Studio REFUSES to load and names this module. \`.jsonValues()\` is root-only
// (locked decision #7): a nested one would silently get no content validation.
// Remove it again with \`pnpm fixtures nested off\`.
export default c.define(
  "/content/nestedJsonValues.val.ts",
  s.object({
    nested: s.record(s.object({ title: s.string() })).jsonValues(),
  }),
  {
    nested: {},
  },
);
`;

function writeFileEnsuringDir(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function listEntryFiles() {
  if (!fs.existsSync(KB_ENTRIES_DIR)) {
    return [];
  }
  return fs
    .readdirSync(KB_ENTRIES_DIR)
    .filter((name) => name.endsWith(".val.json"))
    .sort();
}

function generate(count) {
  if (!Number.isInteger(count) || count < 1) {
    fail(`generate: count must be a positive integer, got ${count}`);
  }
  if (fs.existsSync(KB_ENTRIES_DIR)) {
    fs.rmSync(KB_ENTRIES_DIR, { recursive: true });
  }
  for (let i = 0; i < count; i++) {
    writeFileEnsuringDir(
      path.join(KB_ENTRIES_DIR, entryFileName(i)),
      JSON.stringify(entryContent(i), null, 2) + "\n",
    );
  }
  writeFileEnsuringDir(KB_MODULE, kbModuleSource(count));
  console.log(
    `Generated ${count} kb entries in content/kb/ and rewrote content/kb.val.ts.`,
  );
  if (count > ODD_ONE_OUT_INDEX) {
    console.log(
      `Entry "${entryKey(ODD_ONE_OUT_INDEX)}" is the only referrer of author "kimmid" and route "/support/faq" (V11/V17).`,
    );
  } else {
    console.log(
      `NOTE: with fewer than ${ODD_ONE_OUT_INDEX + 1} entries there is no lone referrer, so V17 needs a bigger count.`,
    );
  }
}

/** Indices whose files are corrupted, spread out so at least one is off-screen. */
function corruptTargets(count, total) {
  const targets = [];
  for (let n = 0; n < count; n++) {
    const index = Math.min(total - 1, Math.round((n * (total - 1)) / count));
    if (!targets.includes(index)) {
      targets.push(index);
    }
  }
  return targets;
}

function corrupt(count) {
  const files = listEntryFiles();
  if (files.length === 0) {
    fail("corrupt: no kb entries on disk — run `pnpm fixtures generate` first");
  }
  const targets = corruptTargets(count, files.length);
  for (const index of targets) {
    fs.writeFileSync(
      path.join(KB_ENTRIES_DIR, entryFileName(index)),
      '{ "title": "broken", this is not valid JSON\n',
    );
  }
  console.log(
    `Corrupted ${targets.length} kb entr${targets.length === 1 ? "y" : "ies"}: ${targets
      .map(entryKey)
      .join(", ")}`,
  );
  console.log("Undo with: pnpm fixtures restore");
}

function restore() {
  const files = listEntryFiles();
  if (files.length === 0) {
    fail("restore: no kb entries on disk — run `pnpm fixtures generate` first");
  }
  let restored = 0;
  for (const name of files) {
    const filePath = path.join(KB_ENTRIES_DIR, name);
    const index = Number(name.slice("entry-".length, name.indexOf(".")));
    const canonical = JSON.stringify(entryContent(index), null, 2) + "\n";
    // Rewrites anything that differs from canonical, not just unparseable files:
    // an entry edited in the Studio (or hand-edited to break schema validation
    // rather than JSON parsing) needs restoring too.
    if (fs.readFileSync(filePath, "utf-8") === canonical) {
      continue;
    }
    fs.writeFileSync(filePath, canonical);
    restored++;
  }
  console.log(
    restored === 0
      ? "Nothing to restore: every kb entry already holds its canonical content."
      : `Restored ${restored} kb entr${restored === 1 ? "y" : "ies"}.`,
  );
}

function readValModules() {
  return fs.readFileSync(VAL_MODULES, "utf-8");
}

function nested(state) {
  if (state !== "on" && state !== "off") {
    fail("nested: expected `on` or `off`");
  }
  const registry = readValModules();
  if (state === "on") {
    fs.writeFileSync(NESTED_MODULE, NESTED_MODULE_SOURCE);
    if (!registry.includes(NESTED_REGISTRY_LINE)) {
      fs.writeFileSync(
        VAL_MODULES,
        registry.replace(/(\n\]\);\s*)$/, `\n${NESTED_REGISTRY_LINE}$1`),
      );
    }
    console.log(
      "Nested jsonValues module added and registered. The Studio should now REFUSE",
    );
    console.log(
      'to load, naming "/content/nestedJsonValues.val.ts" (V9). Turn it off with:',
    );
    console.log("  pnpm fixtures nested off");
    return;
  }
  if (fs.existsSync(NESTED_MODULE)) {
    fs.rmSync(NESTED_MODULE);
  }
  fs.writeFileSync(
    VAL_MODULES,
    registry
      .split("\n")
      .filter((line) => line !== NESTED_REGISTRY_LINE)
      .join("\n"),
  );
  console.log("Nested jsonValues module removed and de-registered.");
}

function git(args) {
  return execFileSync("git", args, {
    cwd: appDir,
    encoding: "utf-8",
  });
}

function reset() {
  // Only the fixture paths: a walkthrough must never be able to throw away
  // unrelated work in progress.
  const dirty = git(["status", "--porcelain", "--", ...FIXTURE_PATHS]).trim();
  git(["checkout", "--", ...FIXTURE_PATHS]);
  git(["clean", "-fdq", "--", ...FIXTURE_PATHS]);
  const patchesDir = path.join(appDir, ".val", "patches");
  const hadPatches = fs.existsSync(patchesDir);
  if (hadPatches) {
    fs.rmSync(patchesDir, { recursive: true });
  }
  console.log(
    dirty
      ? `Reverted fixture files:\n${dirty}`
      : "Fixture files were already clean.",
  );
  console.log(
    hadPatches
      ? "Deleted .val/patches (pending drafts are gone)."
      : "No pending drafts to delete.",
  );
  console.log("Restart the dev server if it was running.");
}

function status() {
  const files = listEntryFiles();
  const invalid = files.filter((name) => {
    try {
      JSON.parse(fs.readFileSync(path.join(KB_ENTRIES_DIR, name), "utf-8"));
      return false;
    } catch {
      return true;
    }
  });
  const patchesDir = path.join(appDir, ".val", "patches");
  const patches = fs.existsSync(patchesDir)
    ? fs.readdirSync(patchesDir).length
    : 0;
  const supportEntries = [
    path.join(appDir, "app", "support", "[slug]", "content"),
    path.join(appDir, "app", "support", "[slug]", "page"),
  ]
    .filter((dir) => fs.existsSync(dir))
    .flatMap((dir) =>
      fs
        .readdirSync(dir, { recursive: true })
        .filter((name) => String(name).endsWith(".val.json"))
        .map((name) => path.join(path.basename(dir), String(name))),
    );
  console.log(`kb entries:            ${files.length}`);
  console.log(
    `  corrupted:           ${invalid.length}${
      invalid.length > 0 ? ` (${invalid.join(", ")})` : ""
    }`,
  );
  console.log(`support entries:       ${supportEntries.length}`);
  for (const entry of supportEntries) {
    console.log(`  ${entry}`);
  }
  console.log(
    `nested jsonValues:     ${fs.existsSync(NESTED_MODULE) ? "ON (Studio should refuse to load)" : "off"}`,
  );
  console.log(`pending draft patches: ${patches}`);
  const dirty = git(["status", "--porcelain", "--", ...FIXTURE_PATHS]).trim();
  console.log(
    dirty ? `dirty fixture files:\n${dirty}` : "dirty fixture files:  none",
  );
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

function usage() {
  console.log(
    [
      "Usage: pnpm fixtures <command>",
      "",
      "  status                 what is on disk right now",
      `  generate [count]       (re)generate the kb record (default ${DEFAULT_ENTRY_COUNT})`,
      `  corrupt [count]        make N kb entries invalid JSON (default ${DEFAULT_CORRUPT_COUNT})`,
      "  restore                un-corrupt them",
      "  nested on|off          add/remove a NESTED jsonValues module (V9)",
      "  reset                  discard all walkthrough edits + pending drafts",
    ].join("\n"),
  );
}

const [command, arg] = process.argv.slice(2);
switch (command) {
  case "generate":
    generate(arg === undefined ? DEFAULT_ENTRY_COUNT : Number(arg));
    break;
  case "corrupt":
    corrupt(arg === undefined ? DEFAULT_CORRUPT_COUNT : Number(arg));
    break;
  case "restore":
    restore();
    break;
  case "nested":
    nested(arg);
    break;
  case "reset":
    reset();
    break;
  case "status":
    status();
    break;
  default:
    usage();
    process.exit(command === undefined || command === "help" ? 0 : 1);
}
