/**
 * What the Studio says about a project's plan, driven by the answers Val
 * Build really sends (`fixtures/`, generated by valbuild/home's
 * `tierStates.test.ts`): the notice above the editor, the status in the top
 * bar, and who gets which button.
 */

/** The moment valbuild/home generated the fixtures at. */
const NOW = new Date("2026-10-09T12:00:00Z");
const FORMAT = { now: NOW, locale: "en-GB", timeZone: "UTC" };
const CTX = { ...FORMAT, project: "website" };

type Who = "owner" | "editor";

const accessOf = (state: keyof typeof ACCESS_FIXTURES, who: Who) => {
  const access = parseStudioAccess(studioAccessBody(state, who));
  if (access === null) throw new Error(`${state} did not parse`);
  return access;
};

const noticeOf = (
  state: keyof typeof ACCESS_FIXTURES,
  who: Who,
  ctx: Partial<typeof CTX> & { changesWaiting?: number } = {},
): PlanNotice | null =>
  planNoticesOf(accessOf(state, who), null, { ...CTX, ...ctx })[0] ?? null;

const mailtoOf = (href: string) => {
  const url = new URL(href);
  return {
    to: url.pathname,
    subject: url.searchParams.get("subject"),
    body: url.searchParams.get("body"),
  };
};

describe("parsing Val Build's answer", () => {
  test.each(Object.keys(ACCESS_FIXTURES))("%s parses", (state) => {
    const access = parseStudioAccess(
      studioAccessBody(state as keyof typeof ACCESS_FIXTURES, "owner"),
    );
    expect(access).not.toBeNull();
    expect(access?.limits).not.toBeNull();
    expect(access?.billingUrl).toBe(BILLING_URL);
    expect(access?.projectUrl).toBe(PROJECT_URL);
    expect(access?.owners).toHaveLength(2);
  });

  test("the limits are read as sent", () => {
    const free = accessOf("access-free-at-limit", "owner").limits;
    expect(free?.plan).toBe("free");
    expect(free?.changes).toEqual({
      used: 1000,
      limit: 1000,
      left: 0,
      warn: false,
      nextAt: "2026-10-14T12:00:00.000Z",
    });
    expect(free?.refused.edit).toEqual({
      code: "limit:changes",
      rawCode: "limit:changes",
      fix: "upgrade",
      until: "2026-10-14T12:00:00.000Z",
    });
    const trial = accessOf("access-hosted-trial", "owner").limits;
    expect(trial?.trial).toEqual({
      status: "running",
      daysLeft: 12,
      publishesLeft: 2,
      endsAt: "2026-10-21T12:00:00.000Z",
      usageShare: null,
    });
    const over = accessOf("access-hosted-trial-over", "owner").limits;
    expect(over?.trial).toEqual({
      status: "over",
      reason: "days",
      endedAt: "2026-10-08T12:00:00.000Z",
      pauseAt: "2026-10-22T12:00:00.000Z",
    });
    const usage = accessOf("access-hosted-usage-warn", "owner").limits?.usage;
    expect(usage?.warn).toEqual(["siteRequests"]);
    expect(usage?.out).toEqual(["renderMs"]);
    expect(usage?.meters).toHaveLength(5);
  });

  test.each(Object.keys(REFUSED_FIXTURES))("%s is a plan refusal", (name) => {
    const refusal = parsePlanRefusal(
      REFUSED_FIXTURES[name as keyof typeof REFUSED_FIXTURES],
    );
    expect(refusal).not.toBeNull();
    expect(refusal?.code).not.toBe("other");
    expect(refusal?.billingUrl).toBe(BILLING_URL);
  });

  test("a 403 that is not about the plan is not a plan refusal", () => {
    expect(parsePlanRefusal({ message: "Unauthorized" })).toBeNull();
    expect(
      parsePlanRefusal({ error: { code: "nonce-expired", message: "x" } }),
    ).toBeNull();
    expect(parsePlanRefusal(undefined)).toBeNull();
  });

  test("a code from a newer Val Build is kept, as `other`", () => {
    expect(
      parsePlanRefusal({
        message: "Something new",
        error: {
          code: "limit:seats",
          fix: "buy-seats",
          billingUrl: "https://admin.val.build/~/acme?section=billing",
        },
      }),
    ).toEqual({
      code: "other",
      rawCode: "limit:seats",
      fix: "other",
      until: null,
      billingUrl: "https://admin.val.build/~/acme?section=billing",
      message: "Something new",
    });
    const access = parseStudioAccess({
      access: "edit",
      limits: {
        plan: "enterprise",
        refused: { edit: { code: "limit:seats", fix: "buy-seats" } },
        trial: { status: "paused-by-moon" },
      },
    });
    expect(access?.limits?.plan).toBe("other");
    expect(access?.limits?.refused.edit?.code).toBe("other");
    expect(access?.limits?.trial).toEqual({ status: "other" });
  });

  test("an older Val Build: no limits and no links is still an answer", () => {
    expect(parseStudioAccess({ access: "edit" })).toEqual({
      plan: { access: "edit" },
      limits: null,
      org: null,
      canFix: false,
      owners: [],
      billingUrl: null,
      projectUrl: null,
    });
    expect(parseStudioAccess({ access: "maybe" })).toBeNull();
    expect(parseStudioAccess("edit")).toBeNull();
  });

  test("a link that is not http(s) is not kept, and a bad owner is skipped", () => {
    const access = parseStudioAccess({
      access: "edit",
      billingUrl: "javascript:alert(1)",
      projectUrl: "https://admin.val.build/~/acme/website",
      owners: [
        { name: "Ada", email: "ada@acme.com" },
        { name: "No email" },
        "who",
      ],
    });
    expect(access?.billingUrl).toBeNull();
    expect(access?.projectUrl).toBe("https://admin.val.build/~/acme/website");
    expect(access?.owners).toEqual([{ name: "Ada", email: "ada@acme.com" }]);
  });
});

